import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultInput = "C:/Users/destr/Downloads/imager/7/Shipped Order Summary On 2026-03-27.xlsx";
const inputPath = process.argv[2] || defaultInput;
const outputPath = process.argv[3] || path.join(projectRoot, "src", "shippedOrders.generated.js");

function asNumber(value) {
  if (value === null || value === undefined || value === "") return null;
  const num = Number(String(value).replace(/,/g, ""));
  return Number.isFinite(num) ? num : null;
}

function asText(value) {
  if (value === null || value === undefined || value === "") return null;
  return String(value).trim() || null;
}

const workbook = XLSX.readFile(inputPath, { raw: false });
const sheetName = workbook.SheetNames[0];
const rows = XLSX.utils.sheet_to_json(workbook.Sheets[sheetName], {
  header: 1,
  defval: null,
  raw: false,
});

const headers = rows[2] || [];
const dataRows = rows.slice(3).filter((row) => row.some((value) => value !== null && value !== ""));

const orders = dataRows.map((row) => {
  const get = (label) => row[headers.indexOf(label)] ?? null;

  return {
    ord: asText(get("Order #")),
    custId: asText(get("Cust #")),
    customer: asText(get("Cust Name")),
    address: asText(get("Del Addr")),
    city: asText(get("City")),
    mix: asText(get("Mix #")),
    description: asText(get("Descr")),
    plantId: asNumber(get("Plant")),
    truck: asText(get("Truck")),
    rate: asNumber(get("Rate")),
    startTime: asText(get("Start Time")),
    travelTime: asNumber(get("Travel Time")),
    orderQty: asNumber(get("Order Qty")),
    deliveredQty: asNumber(get("Delivered Qty")),
    loadSize: asNumber(get("Ld/Sz")),
    status: asText(get("Status")),
    salesmanId: asText(get("Salesman #")),
    date: asText(get("Date")),
    avgLoadSize: asNumber(get("avg_load_size")),
  };
});

const meta = {
  sourceFile: path.basename(inputPath),
  sheetName,
  rowCount: orders.length,
};

const contents = `// Generated by scripts/import-shipped-order-summary.mjs\n\nexport const SHIPPED_ORDER_SUMMARY_META = ${JSON.stringify(meta, null, 2)};\n\nexport const SHIPPED_ORDER_SUMMARY_ORDERS = ${JSON.stringify(orders, null, 2)};\n`;

await fs.writeFile(outputPath, contents, "utf8");

console.log(`Wrote ${orders.length} order rows to ${outputPath}`);
