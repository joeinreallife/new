import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultInput = "C:/Users/destr/Downloads/imager/7/Agg Truck Assign.xlsx";
const inputPath = process.argv[2] || defaultInput;
const outputPath = process.argv[3] || path.join(projectRoot, "src", "aggTruckAssignments.generated.js");

function asText(value) {
  if (value === null || value === undefined || value === "") return null;
  return String(value).trim() || null;
}

const workbook = XLSX.readFile(inputPath, { raw: false });
const sheetName = workbook.SheetNames[0];
const rows = XLSX.utils.sheet_to_json(workbook.Sheets[sheetName], {
  header: 1,
  defval: null,
  raw: false,
});

const headers = rows[0] || [];
const dataRows = rows.slice(1).filter((row) => row.some((value) => value !== null && value !== ""));

const assignments = dataRows.map((row) => {
  const get = (label) => row[headers.indexOf(label)] ?? null;

  return {
    start: asText(get("Start")),
    driver: asText(get("Driver")),
    name: asText(get("Name")),
    tempTruck: asText(get("Temp Tr")),
    assignTruck: asText(get("Assign Tr")),
    type: asText(get("Type")),
    locationCode: asText(get("Loc.")),
    location: asText(get("Truck Location Description")),
  };
});

const meta = {
  sourceFile: path.basename(inputPath),
  sheetName,
  rowCount: assignments.length,
};

const contents = `// Generated by scripts/import-agg-truck-assign.mjs\n\nexport const AGG_TRUCK_ASSIGN_META = ${JSON.stringify(meta, null, 2)};\n\nexport const AGG_TRUCK_ASSIGNMENTS = ${JSON.stringify(assignments, null, 2)};\n`;

await fs.writeFile(outputPath, contents, "utf8");

console.log(`Wrote ${assignments.length} assignment rows to ${outputPath}`);
